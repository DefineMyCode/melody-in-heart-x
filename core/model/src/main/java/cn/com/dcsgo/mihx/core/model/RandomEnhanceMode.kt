package cn.com.dcsgo.mihx.core.model

/**
 * 随心播放增强的运行模式（2026-10-20 探索播放新增）。
 *
 * 时段模式与探索模式互斥（二者只能启用一个），关闭时为普通随机。
 * - [TIME_SLOT]：时段 × 情绪词条，随心播放/无限随机命中时段时按词条过滤候选池（原有行为）。
 * - [EXPLORE]：探索播放——随心播放随机 10 首；无限随机播放被禁用；收听过程中按
 *   收听时长（<30s 或 <1/4 总时长判定为快速跳过）自动积累喜欢/不喜欢词条（计票制）；
 *   队列剩余 1 首时自动补 5 首（须含喜欢词条、尽量不含不喜欢词条）。
 */
enum class RandomEnhanceMode {
    OFF,
    TIME_SLOT,
    EXPLORE,
}
